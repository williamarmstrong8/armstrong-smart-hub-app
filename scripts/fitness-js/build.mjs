#!/usr/bin/env node
// Bundles the hub's pure fitness modules (lib/fitness in the hub repo) and
// entry.js into one script for JavaScriptCore on the phone:
// Armstrong-Smart-Hub-App/Core/Local/fitness.js.
//
//   node scripts/fitness-js/build.mjs [path to the hub's lib/fitness]
//
// Each module's TypeScript types are stripped with Node's own stripper, its
// relative imports become lazy lookups in a small module table, and its
// exports are collected. Re-run it whenever the hub's fitness math changes.
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const hub = resolve(process.argv[2] ?? join(process.env.HOME, "Armstrong-Smart-Hub-google/lib/fitness"));
const out = resolve(here, "../../Armstrong-Smart-Hub-App/Core/Local/fitness.js");

const MODULES = [
  "fit", "physiology", "scores", "insights", "watch-metrics", "summarize",
  "watch-snapshot", "metrics", "insight-metrics", "watch-settings", "checkin-engine",
];

function convert(name) {
  let code = stripTypeScriptTypes(readFileSync(join(hub, `${name}.ts`), "utf8"));
  if (/\bimport\s+(?!\{)[\w*]/.test(code) || /from\s+"(?!\.\/)/.test(code)) throw new Error(`${name}: only relative named imports are supported`);
  code = code.replace(/import\s*\{([^}]*)\}\s*from\s*"\.\/([\w-]+)\.ts";?/g, (_, specs, from) => {
    if (!MODULES.includes(from)) throw new Error(`${name}: imports ./${from}.ts, which isn't bundled`);
    const names = specs.split(",").map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ": "));
    return names.length ? `const { ${names.join(", ")} } = __require(${JSON.stringify(from)});` : "";
  });
  const exported = [];
  code = code.replace(/^export\s+(async\s+function\*?|function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, id) => {
    exported.push(id);
    return `${kind} ${id}`;
  });
  if (/^export\b/m.test(code)) throw new Error(`${name}: an export form this script doesn't handle`);
  return `__modules[${JSON.stringify(name)}] = function () {\n${code}\nreturn { ${exported.join(", ")} };\n};\n`;
}

const prelude = `// Generated by scripts/fitness-js/build.mjs from the hub's lib/fitness. Don't edit by hand.
"use strict";
var __modules = {}, __cache = {};
function __require(name) {
  if (!(name in __cache)) { if (!__modules[name]) throw new Error("missing module " + name); __cache[name] = __modules[name](); }
  return __cache[name];
}
// JavaScriptCore has no TextDecoder; fit.ts only decodes short UTF-8 strings.
if (typeof TextDecoder === "undefined") {
  globalThis.TextDecoder = class {
    decode(bytes) {
      let s = "";
      for (let i = 0; i < bytes.length; i++) s += "%" + bytes[i].toString(16).padStart(2, "0");
      try { return decodeURIComponent(s); } catch { return String.fromCharCode(...bytes); }
    }
  };
}
`;

const body = MODULES.map(convert).join("\n");
const entry = readFileSync(join(here, "entry.js"), "utf8");
writeFileSync(out, `${prelude}\n${body}\n${entry}`);
console.log(`wrote ${out} (${(prelude.length + body.length + entry.length) / 1000 | 0} KB)`);
