#!/usr/bin/env node
// Bundles the pure TypeScript modules in scripts/hub-js/src (the fitness and
// finance math that used to run on the hub, now kept here) into scripts the
// phone runs in JavaScriptCore:
//
//   fitness.js  lib/fitness/* + fitness-entry.js   (FitnessJS / LocalFitness)
//   finance.js  lib/finance, categories, ...  + finance-entry.js  (HubJS / LocalFinance)
//
//   node scripts/hub-js/build.mjs
//
// Tests for the fitness modules: node --test scripts/hub-js/src/tests/
//
// Each module's types are stripped with Node's own stripper, its imports of
// other bundled modules become lazy lookups in a small module table, and its
// exports are collected. Re-run it after changing anything in src/.
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const hub = resolve(process.argv[2] ?? join(here, "src"));
const outDir = resolve(here, "../../Armstrong-Smart-Hub-App/Core/Local");

const BUNDLES = [
  {
    out: "fitness.js",
    entry: "fitness-entry.js",
    modules: [
      "lib/fitness/fit", "lib/fitness/physiology", "lib/fitness/scores", "lib/fitness/insights", "lib/fitness/watch-metrics",
      "lib/fitness/summarize", "lib/fitness/watch-snapshot", "lib/fitness/metrics", "lib/fitness/insight-metrics",
      "lib/fitness/watch-settings", "lib/fitness/checkin-engine",
    ],
  },
  {
    out: "finance.js",
    entry: "finance-entry.js",
    // simplefin.ts is here for institutionName and accountSetErrors; its fetch code is never called.
    modules: ["lib/categories", "lib/simplefin", "lib/finance", "lib/recurring", "lib/goal"],
  },
];

/** "./x.ts" next to the importer, or "@/lib/x", as a module key like "lib/fitness/x". */
function resolveImport(from, spec) {
  if (spec.startsWith("@/")) return spec.slice(2).replace(/\.ts$/, "");
  if (spec.startsWith("./")) return join(dirname(from), spec.slice(2)).replace(/\.ts$/, "");
  return null;
}

function convert(key, modules) {
  const source = readFileSync(join(hub, `${key}.ts`), "utf8");
  let code;
  try {
    code = stripTypeScriptTypes(source);
  } catch {
    // Parameter properties and the like need a real transform, not just stripping.
    code = stripTypeScriptTypes(source, { mode: "transform" });
  }
  code = code.replace(/^import\s+"server-only";?\s*$/m, "");
  code = code.replace(/import\s*\{([^}]*)\}\s*from\s*"([^"]+)";?/g, (_, specs, from) => {
    const target = resolveImport(key, from);
    const names = specs.split(",").map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ": "));
    if (!names.length) return "";
    if (!target || !modules.includes(target)) throw new Error(`${key}: imports ${from}, which isn't bundled`);
    return `const { ${names.join(", ")} } = __require(${JSON.stringify(target)});`;
  });
  if (/^\s*import\s/m.test(code)) throw new Error(`${key}: an import form this script doesn't handle`);
  const exported = [];
  code = code.replace(/^export\s+(async\s+function\*?|function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, id) => {
    exported.push(id);
    return `${kind} ${id}`;
  });
  // Re-exports of imported names: `export { A, B };`
  code = code.replace(/^export\s*\{([^}]*)\};?/gm, (_, names) => {
    exported.push(...names.split(",").map((s) => s.trim()).filter(Boolean));
    return "";
  });
  if (/^export\b/m.test(code)) throw new Error(`${key}: an export form this script doesn't handle`);
  return `__modules[${JSON.stringify(key)}] = function () {\n${code}\nreturn { ${exported.join(", ")} };\n};\n`;
}

const prelude = (name) => `// Generated by scripts/hub-js/build.mjs from scripts/hub-js/src (${name}). Don't edit by hand.
"use strict";
var __modules = {}, __cache = {};
function __require(name) {
  if (!(name in __cache)) { if (!__modules[name]) throw new Error("missing module " + name); __cache[name] = __modules[name](); }
  return __cache[name];
}
// JavaScriptCore has no TextDecoder; the FIT reader only decodes short UTF-8 strings.
if (typeof TextDecoder === "undefined") {
  globalThis.TextDecoder = class {
    decode(bytes) {
      let s = "";
      for (let i = 0; i < bytes.length; i++) s += "%" + bytes[i].toString(16).padStart(2, "0");
      try { return decodeURIComponent(s); } catch { return String.fromCharCode(...bytes); }
    }
  };
}
`;

for (const bundle of BUNDLES) {
  const body = bundle.modules.map((m) => convert(m, bundle.modules)).join("\n");
  const entry = readFileSync(join(here, bundle.entry), "utf8");
  const text = `${prelude(bundle.out)}\n${body}\n${entry}`;
  writeFileSync(join(outDir, bundle.out), text);
  console.log(`wrote ${bundle.out} (${(text.length / 1000) | 0} KB)`);
}
